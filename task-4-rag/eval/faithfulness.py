"""Evaluate RAG answer faithfulness on all 30 gold questions.

Each answer is generated by the configured Task 4 pipeline.  A separate,
evidence-only Qwen call then decomposes the answer into claims and marks every
claim as supported or unsupported by the returned sources.  Progress is
appended to JSONL so an interrupted AutoDL run can resume safely.
"""

from __future__ import annotations

import json
import os
import re
import sys
import time
from pathlib import Path

import requests


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.rag import answer as rag_answer


ROWS_PATH = ROOT / "eval/faithfulness_rows.jsonl"
RESULT_PATH = ROOT / "eval/faithfulness.json"
API_URL = os.getenv("RAG_API_URL", "http://127.0.0.1:11434/api/chat")
MODEL = os.getenv("RAG_MODEL", "qwen2.5:7b-instruct")


def load_gold() -> list[dict]:
    rows = []
    with (ROOT / "data/gold_qa.jsonl").open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def load_completed() -> dict[str, dict]:
    completed = {}
    if not ROWS_PATH.exists():
        return completed
    with ROWS_PATH.open(encoding="utf-8") as handle:
        for line in handle:
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("id") and not row.get("error"):
                completed[row["id"]] = row
    return completed


def parse_json(text: str) -> dict:
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip(), flags=re.I | re.S)
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", text, flags=re.S)
        if match:
            try:
                return json.loads(match.group(0))
            except json.JSONDecodeError:
                pass
        # Models occasionally repeat a formula containing an unescaped
        # backslash.  The verdict booleans remain unambiguous, so recover them
        # rather than discarding an otherwise valid evaluation.
        verdicts = re.findall(r'["\']supported["\']\s*:\s*(true|false)', text, flags=re.I)
        if verdicts:
            return {
                "verdicts": [
                    {"supported": value.lower() == "true", "source_ids": []}
                    for value in verdicts
                ]
            }
        raise ValueError(f"judge did not return parseable verdicts: {text[:200]}")


def judge_faithfulness(question: str, answer: str, sources: list[dict]) -> dict:
    evidence = "\n\n".join(
        f"[资料{index}] {source['text']}" for index, source in enumerate(sources, 1)
    )
    prompt = f"""你是严格的答案忠实性评审员。只能依据给定资料判断，禁止使用自身知识。

请把答案拆成最少数量的、可独立核验的事实性陈述。对每条陈述判断资料是否明确支持；
仅仅与资料不矛盾不算支持。总结句如果只是已支持陈述的直接归纳，可以算支持。

问题：{question}

{evidence}

待评答案：{answer}

在内部完成声明拆分，但不要在输出中重复声明原文，以免公式转义破坏 JSON。
只输出合法 JSON，不要 Markdown 或解释：
{{"verdicts":[{{"supported":true, "source_ids":[1]}}]}}"""
    payload = {
        "model": MODEL,
        "messages": [
            {"role": "system", "content": "你只做基于证据的严格忠实性评估。"},
            {"role": "user", "content": prompt},
        ],
        "stream": False,
        "options": {"temperature": 0, "num_predict": 384, "num_ctx": 6144},
    }
    last_error = None
    for attempt in range(3):
        try:
            response = requests.post(API_URL, json=payload, timeout=300)
            response.raise_for_status()
            content = (response.json().get("message") or {}).get("content", "")
            result = parse_json(content)
            if isinstance(result, list):
                result = {"claims": result, "unsupported_summary": ""}
            if not isinstance(result, dict):
                raise ValueError("judge JSON must be an object or a claim list")
            claims = result.get("claims") or result.get("verdicts")
            if not isinstance(claims, list) or not claims:
                raise ValueError("judge returned no claims")
            normalized = []
            for claim_index, claim in enumerate(claims, 1):
                if not isinstance(claim, dict):
                    continue
                raw_supported = claim.get("supported")
                supported_value = (
                    raw_supported.strip().lower() in {"true", "yes", "1", "支持"}
                    if isinstance(raw_supported, str)
                    else bool(raw_supported)
                )
                raw_source_ids = claim.get("source_ids", [])
                if not isinstance(raw_source_ids, list):
                    raw_source_ids = [raw_source_ids]
                normalized.append(
                    {
                        "claim": str(claim.get("claim") or f"claim_{claim_index}").strip(),
                        "supported": supported_value,
                        "source_ids": [
                            int(value)
                            for value in raw_source_ids
                            if str(value).isdigit() and 1 <= int(value) <= len(sources)
                        ],
                    }
                )
            if not normalized:
                raise ValueError("judge returned no valid claims")
            supported = sum(claim["supported"] for claim in normalized)
            return {
                "claims": normalized,
                "supported_claims": supported,
                "total_claims": len(normalized),
                "faithfulness": supported / len(normalized),
                "unsupported_summary": str(result.get("unsupported_summary", "")).strip(),
            }
        except Exception as exc:
            last_error = exc
            time.sleep(2**attempt)
    raise RuntimeError(f"faithfulness judge failed after retries: {last_error}")


def aggregate(rows: list[dict]) -> dict:
    successful = [row for row in rows if not row.get("error")]
    supported = sum(row["supported_claims"] for row in successful)
    claims = sum(row["total_claims"] for row in successful)
    macro = sum(row["faithfulness"] for row in successful) / max(1, len(successful))
    fully_supported = sum(row["faithfulness"] == 1.0 for row in successful)
    return {
        "method": "Qwen evidence-only claim decomposition against returned RAG sources",
        "model": MODEL,
        "questions_total": len(rows),
        "questions_scored": len(successful),
        "questions_failed": len(rows) - len(successful),
        "supported_claims": supported,
        "total_claims": claims,
        "faithfulness_micro": round(supported / max(1, claims), 4),
        "faithfulness_macro": round(macro, 4),
        "fully_supported_rate": round(fully_supported / max(1, len(successful)), 4),
        "rows": rows,
    }


def main() -> None:
    gold = load_gold()
    completed = load_completed()
    for index, item in enumerate(gold, 1):
        if item["id"] in completed:
            print(f"[{index:02d}/{len(gold)}] resume {item['id']}", flush=True)
            continue
        started = time.time()
        try:
            rag = rag_answer(item["question"])
            judged = judge_faithfulness(item["question"], rag["answer"], rag["sources"])
            row = {
                "id": item["id"],
                "question": item["question"],
                "answer": rag["answer"],
                "sources": [source.get("source") for source in rag["sources"]],
                **judged,
                "elapsed_seconds": round(time.time() - started, 2),
            }
            status = f"faithfulness={row['faithfulness']:.3f}"
        except Exception as exc:
            row = {"id": item["id"], "question": item["question"], "error": str(exc)}
            status = f"ERROR {exc}"
        with ROWS_PATH.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        completed[item["id"]] = row
        print(f"[{index:02d}/{len(gold)}] {item['id']} {status}", flush=True)

    ordered = [completed[item["id"]] for item in gold]
    result = aggregate(ordered)
    RESULT_PATH.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({key: value for key, value in result.items() if key != "rows"}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
